#![no_std]
#![no_main]

use core::panic::PanicInfo;

mod io;

#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    loop {}
}

static ASCII_ART: &[u8] = b"
           +++++[>++[>+>+        ++>++++>++++>++++>++++++
          >++++++>+++++++        ++>+++++++++<<<<<<<<<-]>>
         >+>+>+> >>>+[<]<        -]>>       >++>-->>+>>++>+
        >--<<<<  <<<.....         .>            ....<......
       ...>...   <<.>....                       >.>>>>>.<.
       <<<<..     ..<....                      >..>>>>>.<
      .<<<<.      >>>.<<.                     >>>>>.<.<
      <<<<<       <.>...>                    >>>.>>>.
     <<<.<        <<<..>>                  .>>>>>.<
    <.<<<         <<...>>                 >>>.<<<
   <..<.          ...>...               <<.>..>.
   >>.<.<<...>>...<<...>>...<         <....>>..
  .<<<.>.>>..>.<<.......<....        .....>...
                 <<.>...            .....>...
                 <......           .>>>.<<..
                 <<.>...          .....>...<......>.>>.<.<<<
                 .>......        ..>>...<<....>>.....>.<..>.          
";

#[no_mangle]
pub extern "C" fn kernel() -> ! {
    
    
    io::enable_cursor(false);

    io::clear_vga();

    io::put_vga_string(ASCII_ART);

    loop {
        let scan_code = io::read_key();
        if scan_code == 0x1E {
            io::enable_cursor(true);
            break;
        }
    } 

    loop {}
}